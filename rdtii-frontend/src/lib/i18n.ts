type I18nKey = keyof typeof messages.en;
type Params = Record<string, string | number>;

function normalizeLocale(value: string | null | undefined): Locale {
  return value?.toLowerCase().startsWith("zh") ? "zh" : DEFAULT_LOCALE;
}

export function getLocale(): Locale {
  if (typeof window === "undefined") return DEFAULT_LOCALE;
  return normalizeLocale(
    window.localStorage.getItem("uiLocale") ||
      window.navigator.languages?.[0] ||
      window.navigator.language,
  );
}

export function setLocale(locale: Locale) {
  if (typeof window !== "undefined") {
    window.localStorage.setItem("uiLocale", locale);
    window.dispatchEvent(
      new CustomEvent(LOCALE_CHANGE_EVENT, { detail: locale }),
    );
  }
}

export function t(key: I18nKey, params: Params = {}) {
  const locale = getLocale();
  const template = messages[locale][key] ?? messages.en[key] ?? key;
  return String(template).replace(/\{(\w+)\}/g, (_, name: string) => {
    const value = params[name];
    return value === undefined ? `{${name}}` : String(value);
  });
}
