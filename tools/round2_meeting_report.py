#!/usr/bin/env python3
"""Aggregate Round 2 artifacts into one meeting-ready markdown report.

Collects, per economy, the LATEST self-evaluation report
(outputs/round2_eval_<ECON>_*.json) plus corpus coverage
(data/round2_corpus/manifest.jsonl) and writes
docs/round2-meeting-report.md: coverage table, accuracy table,
per-pillar rollup and honest caveats.

    python tools/round2_meeting_report.py
"""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
OUTPUTS = REPO_ROOT / "outputs"
CORPUS_MANIFEST = REPO_ROOT / "data" / "round2_corpus" / "manifest.jsonl"
REPORT_PATH = REPO_ROOT / "docs" / "round2-meeting-report.md"

ECONOMIES = ["CHN", "IND", "IDN", "LAO", "MNG", "RUS", "THA"]


def _latest_eval(economy: str) -> dict | None:
    pattern = re.compile(rf"round2_eval_{economy}_(\d{{8}}T\d{{6}})\.json$")
    candidates = sorted(
        (p for p in OUTPUTS.glob(f"round2_eval_{economy}_*.json") if pattern.search(p.name)),
        key=lambda p: p.name,
    )
    if not candidates:
        return None
    data = json.loads(candidates[-1].read_text(encoding="utf-8"))
    # Skip pillar-filtered runs — the meeting table wants full-economy numbers.
    if data.get("pillar_filter"):
        full = [c for c in candidates
                if not json.loads(c.read_text(encoding="utf-8")).get("pillar_filter")]
        if not full:
            return None
        data = json.loads(full[-1].read_text(encoding="utf-8"))
    return data


def _corpus_coverage() -> dict[str, tuple[int, int]]:
    cov: dict[str, list[int]] = defaultdict(lambda: [0, 0])
    if CORPUS_MANIFEST.exists():
        for line in CORPUS_MANIFEST.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            rec = json.loads(line)
            cov[rec["economy"]][1] += 1
            if rec.get("status") in ("ok", "cached"):
                cov[rec["economy"]][0] += 1
    return {k: (v[0], v[1]) for k, v in cov.items()}


def build_report() -> str:
    coverage = _corpus_coverage()
    evals = {e: _latest_eval(e) for e in ECONOMIES}

    lines: list[str] = []
    lines.append("# Round 2 progress — meeting report")
    lines.append("")
    lines.append("_Auto-generated by `tools/round2_meeting_report.py`; every number is"
                 " reproducible from the eval JSONs in `outputs/`._")
    lines.append("")

    lines.append("## Corpus coverage (official baseline laws fetched locally)")
    lines.append("")
    lines.append("| Economy | Laws local / total | % |")
    lines.append("|---|---|---|")
    for e in ECONOMIES:
        ok, total = coverage.get(e, (0, 0))
        pct = f"{100 * ok // total}%" if total else "—"
        lines.append(f"| {e} | {ok} / {total} | {pct} |")
    lines.append("")

    lines.append("## Self-evaluation vs the official Round 2 database")
    lines.append("")
    lines.append("_Every locally fetched baseline law runs through the real pipeline"
                 " (extraction targeted at its officially mapped indicators, deterministic"
                 " scoring); our score is compared to the official raw score."
                 " No evidence found counts as score 0 per RDTII semantics._")
    lines.append("")
    completed_evals = [ev for ev in evals.values() if ev is not None]
    totals = {
        "rows": sum(ev["rows_evaluated"] for ev in completed_evals),
        "evidence": sum(ev["evidence_yield"] for ev in completed_evals),
        "exact": sum(ev["exact_score_matches"] for ev in completed_evals),
    }
    if totals["rows"]:
        evidence_rate = 100 * totals["evidence"] / totals["rows"]
        exact_rate = 100 * totals["exact"] / totals["rows"]
        lines.append(
            f"**Headline benchmark: {totals['rows']} rows evaluated · "
            f"{totals['evidence']} evidence-backed ({evidence_rate:.1f}%) · "
            f"{totals['exact']} exact score matches ({exact_rate:.1f}%).**"
        )
        lines.append(
            "Exact matches include correct abstentions where both the pipeline "
            "and official raw score are zero; this is not a standalone "
            "extraction-accuracy rate."
        )
        lines.append("")
    lines.append("| Economy | Baseline rows | Rows evaluated | Evidence found | Exact score match | MAE |")
    lines.append("|---|---|---|---|---|---|")
    pillar_roll: dict[str, dict[str, int]] = defaultdict(lambda: {"rows": 0, "evidence": 0, "exact": 0})
    for e in ECONOMIES:
        ev = evals[e]
        if ev is None:
            lines.append(f"| {e} | — | — | — | — | (not yet run) |")
            continue
        rate = ev.get("exact_match_rate")
        lines.append(
            f"| {e} | {ev['baseline_rows']} | {ev['rows_evaluated']} "
            f"| {ev['evidence_yield']} "
            f"| {ev['exact_score_matches']} ({round(100 * (rate or 0))}%) "
            f"| {ev.get('mean_absolute_error', '—')} |"
        )
        for pillar, stats in ev.get("per_pillar", {}).items():
            roll = pillar_roll[pillar]
            roll["rows"] += stats["rows"]
            roll["evidence"] += stats["evidence"]
            roll["exact"] += stats["exact"]
    lines.append("")

    if pillar_roll:
        lines.append("## Per-pillar rollup (all evaluated economies)")
        lines.append("")
        lines.append("| Pillar | Rows | Evidence found | Exact matches |")
        lines.append("|---|---|---|---|")
        for pillar in sorted(pillar_roll, key=int):
            r = pillar_roll[pillar]
            lines.append(f"| P{pillar} | {r['rows']} | {r['evidence']} | {r['exact']} |")
        lines.append("")

    lines.append("## Honest caveats")
    lines.append("")
    lines.append("- Rows without locally fetched text are not evaluated (coverage above);"
                 " RUS/MNG are capped by JS-only portals — a browser-path refetch is in progress.")
    lines.append("- `Exact score match` compares against the official raw score at row level;"
                 " counting-rule indicators (e.g. 1.4) aggregate across measures, so row-level"
                 " comparison understates agreement.")
    lines.append("- Non-English statutes are extracted in their original language; extraction"
                 " quality varies by language and is visible per-pillar above.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    REPORT_PATH.parent.mkdir(exist_ok=True)
    report = build_report()
    REPORT_PATH.write_text(report, encoding="utf-8")
    print(report)
    print(f"\nwritten: {REPORT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
